import os
import json
from google.cloud import storage

WORKSPACE_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))

# =====================================================================
# INTERNAL HELPER FUNCTIONS (Not directly callable by Agents)
# =====================================================================

def _get_bucket():
    """
    Internal Helper: GCS Perimeter Connector.
    Purpose: Initializes the Google Cloud Storage bucket connection using ambient 
    enterprise credentials. Defaults to 'npt-fleet-cargo-hold'.
    Invoked By: Called internally by all cloud storage tools.
    """
    bucket_name = os.getenv("GCP_BUCKET_NAME", "npt-fleet-cargo-hold")
    client = storage.Client()
    return client.bucket(bucket_name)


# =====================================================================
# AGENT TOOLS (Exposed via tool_dispatcher.py)
# =====================================================================

def list_knowledge_artifacts() -> str:
    """
    Agent Tool: GCS Directory Listing.
    Purpose: Lists all persistent forensic documents currently held in the cloud bucket.
    Invoked By: General diagnostic tool available to multiple agents if they need to verify 
    the presence of an artifact in the Cargo Hold.
    """
    try:
        bucket = _get_bucket()
        blobs = bucket.list_blobs()
        names = [blob.name for blob in blobs]
        
        if not names:
            return "[NOTICE] The cloud cargo hold is currently empty."
            
        return "Cloud Knowledge Artifacts:\n" + "\n".join([f"- {name}" for name in names])
    except Exception as e:
        return f"[ERROR] Failed to read GCS bucket: {str(e)}"


def read_knowledge_artifact(artifact_name: str) -> str:
    """
    Agent Tool: The Bronze Text Extractor.
    Purpose: Reads the exact verbatim text of a specified knowledge artifact.
    Optimized for single-path reading: checks local canonical path first (0 network latency),
    falling back to GCS streaming if the local copy is not present.
    Invoked By: CUTLASS (Epistemic Auditor), GROG (Structural Extraction), 
    PLANK (Ontology Mapping), and BILGELADLE (Thesis Alignment).
    """
    try:
        clean_name = (artifact_name or "").strip()
        if clean_name.startswith("gs://"):
            clean_name = clean_name[5:]
        bucket = _get_bucket()
        if bucket.name and clean_name.startswith(f"{bucket.name}/"):
            clean_name = clean_name[len(bucket.name) + 1:]
        elif clean_name.startswith("npt-fleet-cargo-hold/"):
            clean_name = clean_name[len("npt-fleet-cargo-hold/"):]

        # Fast path: check local workspace first (zero network latency)
        local_path = os.path.abspath(os.path.join(WORKSPACE_ROOT, clean_name))
        if os.path.exists(local_path) and os.path.isfile(local_path):
            with open(local_path, "r", encoding="utf-8", errors="replace") as f:
                return f.read()

        # Fallback path: stream from GCS
        blob = bucket.blob(clean_name)
        if not blob.exists():
            return f"[ERROR] Artifact '{clean_name}' not found in local workspace or GCS."
            
        return blob.download_as_text(encoding="utf-8")
    except Exception as e:
        return f"[ERROR] Failed to read artifact: {str(e)}"


def upsert_knowledge_artifact(artifact_name: str, content: str = "", local_cache_path: str = "") -> str:
    """
    Agent Tool: The Cargo Uploader & Single-Path Cache Manager.
    Purpose: Streams the extracted payload into the cloud cargo hold.
    Crucially, it handles clean single-path staging:
    - Accepts 'local_cache_path' (generated by download_url) or direct 'content'.
    - Uploads the text payload directly to GCS (bucket 'npt-fleet-cargo-hold').
    - Stages a local copy to the canonical path (e.g. 'acquisitions/[slug].txt') so downstream agents can read locally with 0 latency.
    - Cleans up any transient 'cargo_cache/temp_acquire_*.txt' buffer.
    Invoked By: SPYGLASS (The Ingestion Engine).
    """
    try:
        clean_artifact = (artifact_name or "").strip()
        if clean_artifact.startswith("gs://"):
            clean_artifact = clean_artifact[5:]
        bucket = _get_bucket()
        if bucket.name and clean_artifact.startswith(f"{bucket.name}/"):
            clean_artifact = clean_artifact[len(bucket.name) + 1:]
        elif clean_artifact.startswith("npt-fleet-cargo-hold/"):
            clean_artifact = clean_artifact[len("npt-fleet-cargo-hold/"):]

        upload_string = content
        target_path = local_cache_path
        if content and isinstance(content, str) and os.path.exists(content) and content.endswith(".txt"):
            target_path = content

        # Read the file from target path
        if target_path and os.path.exists(target_path):
            with open(target_path, 'r', encoding='utf-8', errors='replace') as f:
                upload_string = f.read()

        if not upload_string:
            return "[ERROR] No content or valid local_cache_path provided."

        # 1. ACTUAL GCP UPLOAD LOGIC
        blob = bucket.blob(clean_artifact)
        blob.upload_from_string(upload_string, content_type="text/plain; charset=utf-8")

        # 2. CANONICAL LOCAL STAGING (Zero-latency read for downstream agents)
        canonical_local = os.path.abspath(os.path.join(WORKSPACE_ROOT, clean_artifact))
        os.makedirs(os.path.dirname(canonical_local), exist_ok=True)
        with open(canonical_local, "w", encoding="utf-8") as f:
            f.write(upload_string)

        # 3. CLEAN UP TRANSIENT SCRAPE BUFFER (cargo_cache/temp_acquire_*.txt)
        if target_path and os.path.exists(target_path):
            abs_target = os.path.abspath(target_path)
            # Only remove if it's a temporary buffer in cargo_cache, not the canonical file itself
            if "cargo_cache" in abs_target and abs_target != canonical_local:
                try:
                    os.remove(abs_target)
                except Exception:
                    pass

        return json.dumps({
            "status": "SUCCESS",
            "artifact_name": clean_artifact,
            "gcs_uri": f"gs://{bucket.name}/{clean_artifact}",
            "local_path": clean_artifact,
            "message": f"Successfully uploaded to GCS and staged locally to {clean_artifact}"
        }, indent=2)

    except Exception as e:
        return f"[ERROR] Upload stream rejected: {str(e)}"


def delete_knowledge_artifact(artifact_name: str) -> str:
    """
    Agent Tool: The GCS Blob Purger.
    Purpose: Permanently deletes a knowledge artifact from the cloud bucket (e.g. when
    incinerating truncated paywall stubs or corrupted assets).
    """
    try:
        bucket = _get_bucket()
        clean_name = (artifact_name or "").strip()
        if clean_name.startswith("gs://"):
            clean_name = clean_name[5:]
        if bucket.name and clean_name.startswith(f"{bucket.name}/"):
            clean_name = clean_name[len(bucket.name) + 1:]
        elif clean_name.startswith("npt-fleet-cargo-hold/"):
            clean_name = clean_name[len("npt-fleet-cargo-hold/"):]

        blob = bucket.blob(clean_name)
        if blob.exists():
            blob.delete()
            return f"[SUCCESS] Artifact '{clean_name}' deleted from GCS."
        return f"[NOTICE] Artifact '{clean_name}' does not exist in GCS."
    except Exception as e:
        return f"[ERROR] Failed to delete artifact '{artifact_name}': {str(e)}"