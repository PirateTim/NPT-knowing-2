"""
NPT Fleet: Gateway A Discovery Engine Matcher (Ship -> Cargo)
Executes the search nets generated by SOP-08 envelopes against GCP Vertex AI Search
(npt-cargo-search-app over gs://npt-fleet-cargo-hold/acquisitions/*.txt)
and resolves candidate documents against cargo.content_metadata.
"""

import os
import sys
import json
import urllib.parse
from typing import Dict, Any, List
import requests
import google.auth
import google.auth.transport.requests
import pg8000.dbapi
from dotenv import load_dotenv

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

load_dotenv(override=True)

DISCOVERY_ENGINE_URL = "https://discoveryengine.googleapis.com/v1/projects/npt-reckoning-1/locations/global/collections/default_collection/engines/npt-cargo-search-app/servingConfigs/default_search:search"

def get_cargo_db_connection():
    conn_string = os.getenv("CONTENT_DATABASE_URL")
    if not conn_string:
        raise ValueError("CONTENT_DATABASE_URL environment variable is not set.")
    url = urllib.parse.urlparse(conn_string)
    return pg8000.dbapi.connect(
        user=url.username,
        password=url.password,
        host=url.hostname,
        port=url.port or 5432,
        database=url.path.lstrip("/")
    )

def get_gcp_bearer_token() -> str:
    credentials, _ = google.auth.default(scopes=["https://www.googleapis.com/auth/cloud-platform"])
    auth_req = google.auth.transport.requests.Request()
    credentials.refresh(auth_req)
    return credentials.token

def query_discovery_engine(query_str: str, page_size: int = 5) -> List[Dict[str, Any]]:
    """Queries Vertex AI Search datastore npt-cargo-poc."""
    token = get_gcp_bearer_token()
    headers = {
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
        "x-goog-user-project": "npt-reckoning-1"
    }
    payload = {
        "query": query_str,
        "pageSize": page_size,
        "contentSearchSpec": {
            "snippetSpec": {"returnSnippet": True}
        },
        "queryExpansionSpec": {"condition": "AUTO"},
        "spellCorrectionSpec": {"mode": "AUTO"}
    }
    try:
        resp = requests.post(DISCOVERY_ENGINE_URL, headers=headers, json=payload, timeout=20)
        if resp.status_code == 200:
            return resp.json().get("results", [])
        else:
            print(f"[DISCOVERY ENGINE ERROR {resp.status_code}] {resp.text}", file=sys.stderr)
            return []
    except Exception as e:
        print(f"[DISCOVERY ENGINE EXCEPTION] {e}", file=sys.stderr)
        return []

def resolve_cargo_metadata(conn, gcs_uri: str) -> Dict[str, Any]:
    """Finds the metadata record matching a GCS bucket path."""
    cursor = conn.cursor()
    # Normalize URI e.g. gs://npt-fleet-cargo-hold/acquisitions/foo.txt -> acquisitions/foo.txt
    rel_path = gcs_uri.replace("gs://npt-fleet-cargo-hold/", "")
    cursor.execute(
        """
        SELECT id, title, source_url, publication_date, substring(abstract from 1 for 180)
        FROM cargo.content_metadata
        WHERE gcp_bucket_path = %s OR gcp_bucket_path LIKE %s
        LIMIT 1
        """,
        (rel_path, f"%{os.path.basename(rel_path)}")
    )
    row = cursor.fetchone()
    cursor.close()
    if row:
        return {
            "metadata_id": row[0],
            "title": row[1],
            "source_url": row[2],
            "publication_date": row[3],
            "abstract_snippet": row[4]
        }
    return {
        "metadata_id": None,
        "title": os.path.basename(rel_path),
        "source_url": gcs_uri,
        "publication_date": None,
        "abstract_snippet": None
    }

def run_gateway_a_for_section(section_number: str = "8.3"):
    conn = get_cargo_db_connection()
    cursor = conn.cursor()
    
    print("\n" + "="*80)
    print(f"[GATEWAY A] DISCOVERY ENGINE SEARCH (SECTION {section_number})")
    print(f"Target App: npt-cargo-search-app | Index: gs://npt-fleet-cargo-hold/acquisitions/*.txt")
    print("="*80)
    
    cursor.execute(
        """
        SELECT chunk_id, paragraph_sequence_number, lexical_envelope
        FROM ship.letters_of_marque
        WHERE section_number = %s
        ORDER BY paragraph_sequence_number
        """,
        (section_number,)
    )
    chunks = cursor.fetchall()
    cursor.close()
    
    if not chunks:
        print(f"[ERROR] No chunks found for section {section_number} in ship.letters_of_marque.")
        conn.close()
        return

    all_matches = []

    for chunk_id, p_num, envelope in chunks:
        if not envelope:
            print(f"\n[{chunk_id}] (Paragraph {p_num}) No envelope found. Skipping.")
            continue
            
        summary = envelope.get("paragraph_summary", "")
        boolean_query = envelope.get("search_query", "")
        probes = envelope.get("embedding_probes", [])
        
        print(f"\n" + "-"*80)
        print(f"--- [{chunk_id}] Paragraph {p_num} ---")
        print(f"   Summary: {summary}")
        print(f"   Primary Net (Boolean): {boolean_query[:100]}...")
        
        # 1. First probe: Test Boolean search net
        results = query_discovery_engine(boolean_query, page_size=3)
        query_used = "Boolean Query"
        
        # 2. Fallback probe: If Boolean returns 0 results (due to over-constraint), try top dense embedding probe
        if not results and probes:
            fallback_probe = probes[0]
            print(f"   [NOTICE] Boolean net yielded 0 hits. Firing dense probe: '{fallback_probe}'...")
            results = query_discovery_engine(fallback_probe, page_size=3)
            query_used = f"Dense Probe: '{fallback_probe}'"

        print(f"   [RESULTS] Found {len(results)} candidate cargo documents (via {query_used}):")
        
        chunk_matches = []
        for rank, res in enumerate(results, 1):
            doc = res.get("document", {})
            struct_data = doc.get("derivedStructData", {})
            gcs_link = struct_data.get("link", "")
            snippets = struct_data.get("snippets", [])
            snippet_text = snippets[0].get("snippet", "") if snippets else ""
            
            meta = resolve_cargo_metadata(conn, gcs_link)
            
            match_info = {
                "rank": rank,
                "gcs_link": gcs_link,
                "metadata_id": meta["metadata_id"],
                "title": meta["title"],
                "url": meta["source_url"],
                "snippet": snippet_text
            }
            chunk_matches.append(match_info)
            
            meta_label = f"Metadata ID {meta['metadata_id']}" if meta['metadata_id'] else "Uncataloged GCS"
            print(f"     {rank}. [{meta_label}] {meta['title']}")
            print(f"        Link: {gcs_link}")
            if snippet_text:
                clean_snippet = snippet_text.replace("<b>", "").replace("</b>", "").strip()[:140]
                print(f"        Snippet: \"{clean_snippet}...\"")
                
        all_matches.append({
            "chunk_id": chunk_id,
            "paragraph_sequence_number": p_num,
            "summary": summary,
            "matches": chunk_matches
        })

    conn.close()
    print("\n" + "="*80)
    print(f"[COMPLETE] Gateway A execution complete for Section {section_number} ({len(all_matches)} chunks scanned).")
    print("="*80)
    return all_matches

if __name__ == "__main__":
    section = sys.argv[1] if len(sys.argv) > 1 else "8.3"
    run_gateway_a_for_section(section)
